import { jsPDF } from "jspdf";

/**
 * Downloads formatted text content as a clean PDF document.
 */
export function exportPDF(title: string, content: string) {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 15;
  const maxLineWidth = pageWidth - margin * 2;

  // Header Banner
  doc.setFillColor(30, 41, 59); // Slate-800
  doc.rect(0, 0, pageWidth, 25, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text("ZION DIGITAL ACADEMIC & EVANGELISM LEDGER", margin, 12);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text("Bungoma Regional Study Hub • Published Document", margin, 18);

  // Document Title
  let currentY = 35;
  doc.setTextColor(15, 23, 42); // Slate-900
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);

  const titleLines = doc.splitTextToSize(title || "Untitled Document", maxLineWidth);
  doc.text(titleLines, margin, currentY);
  currentY += titleLines.length * 8 + 4;

  // Divider
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(margin, currentY, pageWidth - margin, currentY);
  currentY += 8;

  // Document Content
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.setTextColor(51, 65, 85);

  const paragraphs = (content || "No text provided.").split("\n");

  paragraphs.forEach((paragraph) => {
    if (!paragraph.trim()) {
      currentY += 4;
      return;
    }

    const lines = doc.splitTextToSize(paragraph, maxLineWidth);
    
    // Check page overflow
    if (currentY + lines.length * 6 > pageHeight - margin) {
      doc.addPage();
      currentY = margin + 10;
      
      // Page watermark header
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(`${title} - Continued`, margin, margin);
      doc.setFontSize(11);
      doc.setTextColor(51, 65, 85);
    }

    doc.text(lines, margin, currentY);
    currentY += lines.length * 6 + 3;
  });

  // Footer page numbers
  const pageCount = doc.internal.pages.length - 1;
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(`Page ${i} of ${pageCount} • Zion Digital Hub`, pageWidth / 2, pageHeight - 8, { align: "center" });
  }

  const safeFilename = (title || "document").toLowerCase().replace(/[^a-z0-9]/g, "_") + ".pdf";
  doc.save(safeFilename);
}

/**
 * Downloads formatted text as a Word document (.docx) compatible file.
 */
export function exportWordDoc(title: string, content: string) {
  const safeTitle = title || "Zion_Document";
  const formattedText = (content || "No text provided.")
    .split("\n")
    .map((line) => `<p style="font-family: Arial, sans-serif; font-size: 11pt; line-height: 1.5; color: #1e293b; margin-bottom: 8pt;">${line || "&nbsp;"}</p>`)
    .join("");

  const wordDocumentHTML = `
    <html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>
    <head>
      <meta charset='utf-8'>
      <title>${safeTitle}</title>
      <style>
        body { font-family: 'Calibri', 'Segoe UI', Arial, sans-serif; margin: 1in; padding: 0; }
        h1 { color: #0f172a; font-size: 22pt; margin-bottom: 12pt; border-bottom: 2px solid #2563eb; padding-bottom: 6pt; }
        .header-meta { font-size: 9pt; color: #64748b; margin-bottom: 18pt; text-transform: uppercase; font-weight: bold; }
        .footer { margin-top: 30pt; font-size: 9pt; color: #94a3b8; border-top: 1px solid #e2e8f0; padding-top: 8pt; text-align: center; }
      </style>
    </head>
    <body>
      <div class="header-meta">ZION DIGITAL ACADEMIC & EVANGELISM LEDGER • BUNGOMA HUB</div>
      <h1>${safeTitle}</h1>
      <div class="content">${formattedText}</div>
      <div class="footer">Generated by Zion Digital AI Gateway • Official Certified Export</div>
    </body>
    </html>
  `;

  const blob = new Blob(['\ufeff' + wordDocumentHTML], {
    type: 'application/msword;charset=utf-8'
  });

  const safeFilename = safeTitle.toLowerCase().replace(/[^a-z0-9]/g, "_") + ".docx";
  const downloadUrl = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = downloadUrl;
  a.download = safeFilename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(downloadUrl);
}
